    throw "Unsupported DarkSoulsRemastered.exe (SHA-256 $exeHash). This patch only supports the 2018-05-22 build ($ExeSha256)."
}
if (-not (Test-Path $dll)) { throw "d3d11.dll not found in '$dir'. Install DSROmniRoll Standalone v1.01 first." }

$dllHash = (Get-FileHash $dll -Algorithm SHA256).Hash
if ($dllHash -eq $PatchedSha256) {
    Write-Host 'd3d11.dll is already patched. Nothing to do.'
} elseif ($dllHash -ne $OrigSha256) {
    throw "d3d11.dll is not DSROmniRoll Standalone v1.01 (SHA-256 $dllHash, expected $OrigSha256)."
} else {
    $bytes = [IO.File]::ReadAllBytes($dll)
    foreach ($row in $PatchTable) {
        $offset = [int]$row[0]
        $old = Convert-HexToBytes $row[1]
        $new = Convert-HexToBytes $row[2]
        for ($i = 0; $i -lt $old.Length; $i++) {
            if ($bytes[$offset + $i] -ne $old[$i]) { throw ('Unexpected byte at offset 0x{0:X}.' -f ($offset + $i)) }
            $bytes[$offset + $i] = $new[$i]
        }
    }
    $newHash = Get-Sha256Hex $bytes
    if ($newHash -ne $PatchedSha256) { throw "Patched result has SHA-256 $newHash, expected $PatchedSha256. Nothing was written." }
    if (-not (Test-Path $bak)) { Copy-Item $dll $bak }
    [IO.File]::WriteAllBytes($dll, $bytes)
    Write-Host "Patched d3d11.dll ($($PatchTable.Count) changes). Original saved as d3d11.dll.orig."
}

if ($AllowSessionAttempt) {
    if (-not (Test-Path $ini)) { throw "DSROmniRoll.ini not found in '$dir'." }
