function Get-Sha256Hex([byte[]]$Bytes) {
    $sha = [System.Security.Cryptography.SHA256]::Create()
    try { return ([BitConverter]::ToString($sha.ComputeHash($Bytes))).Replace('-', '') }
    finally { $sha.Dispose() }
}

function Convert-HexToBytes([string]$Hex) {
    $out = New-Object byte[] ($Hex.Length / 2)
    for ($i = 0; $i -lt $out.Length; $i++) { $out[$i] = [Convert]::ToByte($Hex.Substring($i * 2, 2), 16) }
    return ,$out
}

function Find-GameDir {
    if ($GameDir) { return $GameDir }
    foreach ($candidate in @($PSScriptRoot, (Split-Path $PSScriptRoot -Parent))) {
        if (Test-Path (Join-Path $candidate 'DarkSoulsRemastered.exe')) { return $candidate }
    }
    return (Read-Host 'Folder that contains DarkSoulsRemastered.exe')
}

$dir = Find-GameDir
